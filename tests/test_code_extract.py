"""The model-free half of the crawler: file choice, generated-file detection, extraction,
the secret filter and areas. No database, no model."""

from __future__ import annotations

from homegrown.extract import code


def test_source_files_exclude_tests_vendored_build_and_config():
    assert code.is_source("src/payments/refund.py")
    assert code.is_source("pkg/client/client.go")
    for p in ("tests/test_refund.py", "src/refund_test.go", "node_modules/x/index.js",
              "dist/app.js", "vendor/lib/a.go", "webpack.config.js", "scripts/release.py",
              "src/app.min.js", "docs/conf.py", "README.md", "src/migrations/0001.py"):
        assert not code.is_source(p), p


def test_generated_and_minified_detected_by_content_not_size():
    assert code.looks_generated("// Code generated by protoc. DO NOT EDIT.\npackage x\n")
    assert code.looks_generated("var a=1;" * 2000)                     # one huge line
    big_real = "\n".join(f"def handler_{i}(request):\n    return {i}" for i in range(20000))
    assert len(big_real) > 300_000 and not code.looks_generated(big_real)


def test_extract_keeps_declarations_and_doc_comments_only():
    src = '''# Copyright 2024 Someone
import os

def refund(order_id: str, amount: int) -> Receipt:
    """Refund part of an order."""
    x = compute()
    return x

class RefundClient:
    pass
'''
    out = code.extract(src)
    assert "def refund(order_id: str, amount: int) -> Receipt:" in out
    assert "class RefundClient:" in out
    assert "x = compute()" not in out and "Copyright" not in out and "import os" not in out


def test_secret_filter_removes_keys_tokens_credentials_and_internal_hosts():
    # Fake, token-shaped values, assembled at runtime so no secret scanner mistakes the
    # source for a leaked credential.
    gh = "gh" + "p_" + "a" * 36
    aws = "AK" + "IA" + "ABCDEFGHIJKLMNOP"
    jwt = ("ey" + "JhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0."
           "dozjgNryP4J3jVmNHl0w5N_XgL0n3I9PSR5h")
    text = f'''
API_KEY = "abcd1234efgh5678ijkl"
token: '{gh}'
aws = {aws}
url = "postgres://admin:hunter2@db.prod.internal:5432/app"
host = "10.2.3.4"
jwt = {jwt}
def connect(host: str) -> Client:
'''
    out = code.scrub(text)
    for leaked in ("abcd1234efgh5678ijkl", gh[:8], aws, "hunter2",
                   "db.prod.internal", "10.2.3.4", jwt[:20]):
        assert leaked not in out, leaked
    assert "def connect(host: str) -> Client:" in out


def test_areas_merge_to_three_levels_share_the_cap_and_drop_tiny_ones():
    ex = {f"src/pay/refund/sub/f{i}.py": "def f():\n" + "x" * 400 for i in range(40)}
    ex["src/tiny/a.py"] = "def a():"
    areas = code.build_areas(ex)
    assert set(areas) == {"src/pay/refund"}
    a = areas["src/pay/refund"]
    assert len(a["text"]) <= code.AREA_MAX_CHARS and len(a["files"]) == 40
    assert a["text"].count("## f") == 40            # every file kept a share
    assert code.build_areas(ex)["src/pay/refund"]["hash"] == a["hash"]


def test_code_words_keep_identifiers_and_add_their_parts():
    out = code.code_words("export function getUserToken(http_retry.backoff) {}\nclass XMLParser")
    assert "getUserToken get user token" in out
    assert "http_retry.backoff http retry backoff" in out
    assert "XMLParser xml parser" in out
    assert code.split_identifier("parseHTTPResponse2") == "parse http response 2"
