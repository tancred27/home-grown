"""Reading source code without a model: which files, what to keep, and areas.

The crawler reads code because READMEs go stale. This module is the free part:
  * pick source files by rules (no tests, vendored or build output, configs, generated
    or minified files; generated and minified are detected from the content, not size).
    Infrastructure code, scripts, notebooks and deployment templates count as source: many
    repos (IaC modules, automation, samples) have nothing else;
  * keep declaration lines and doc comments (public functions, types, classes, exports;
    resources, variables and parameters in infrastructure code), without licence headers;
  * remove anything that looks like a secret or an internal hostname before the text is
    stored or sent to a model;
  * group files into areas (folders merged to at most three path levels).

Source text is untrusted data: nothing here executes it.
"""

from __future__ import annotations

import hashlib
import json
import re
from pathlib import PurePosixPath

SOURCE_EXT = (".py", ".go", ".java", ".kt", ".scala", ".ts", ".tsx", ".js", ".jsx", ".rs",
              ".rb", ".cs", ".c", ".cc", ".cpp", ".h", ".hpp", ".swift", ".php", ".m")
# Infrastructure code, scripts and notebooks: their declarations are resources, parameters and
# functions (see _IAC).
IAC_EXT = (".tf", ".hcl", ".bicep", ".ps1", ".psm1", ".sh", ".bash", ".rego", ".sql", ".ipynb",
           ".r", ".cue", ".sentinel")
# YAML/JSON only where the path says deployment template (CloudFormation, SAM, ARM, GitHub
# Action); extract() then checks the content, so other config files yield nothing.
_TEMPLATE_PATH = re.compile(
    r"((^|/)(templates?|cfn|cloudformation|arm|infra|infrastructure|deploy|deployment)/[^/]+"
    r"|(template|cfn|stack|azuredeploy|maintemplate|serverless)[^/]*|(^|/)action)\.(ya?ml|json)$",
    re.I)
_TEMPLATE_BODY = re.compile(r"AWSTemplateFormatVersion|deploymentTemplate|^Resources:"
                            r"|\"Resources\"\s*:|^runs:|Transform:\s*AWS::Serverless", re.M)

_SKIP_ALWAYS = (
    r"(^|/)(tests?|__tests__|spec|specs|testdata|fixtures?|mocks?|docs?"
    r"|vendor|third_party|node_modules|dist|build|target|generated|gen|\.github|\.terraform)(/|$)"
    r"|(_test|\.test|\.spec|\.tests|_pb2|\.pb|\.min|\.d)\.[a-z0-9]+$|(^|/)test_[^/]*$")
# Examples and samples are skipped unless the repo has no other code (is_source(relaxed=True)).
_SKIP = re.compile(_SKIP_ALWAYS + r"|(^|/)(examples?|samples?|demo)(/|$)", re.I)
_SKIP_RELAXED = re.compile(_SKIP_ALWAYS, re.I)
_NOISE_ALWAYS = (
    r"(^|/)(\.[^/]+|conftest\.py|setup\.py|noxfile\.py|fabfile\.py|gulpfile\.[a-z]+|gruntfile\.[a-z]+"
    r"|webpack[^/]*|rollup\.[^/]+|vite\.[^/]+|jest\.[^/]+|babel\.[^/]+|karma\.[^/]+|tailwind\.[^/]+"
    r"|[^/]*\.config\.[a-z]+|[^/]*\.conf\.[a-z]+)$"
    r"|(^|/)(__pycache__|\.cache|coverage|migrations?|bower_components|__snapshots__"
    r"|benchmarks?|e2e|config|configs)(/|$)|(^|/)\.[^/]+/"
    r"|zz_generated|\.pb\.gw\.")
_NOISE = re.compile(_NOISE_ALWAYS + r"|^(scripts?|tools?|hack|ci)/", re.I)
_NOISE_RELAXED = re.compile(_NOISE_ALWAYS, re.I)
_GENERATED = re.compile(r"DO NOT EDIT|auto-?generated|generated by|@generated", re.I)

# Declaration-like lines and doc comments, language-agnostic.
_DECL = re.compile(
    r"^\s*(///?|/\*\*|\*(?!/)|#(?!include|define|if|endif|pragma)|\"\"\"|export\s|pub(\(crate\))?\s"
    r"|public\s|protected\s|func\s|type\s|class\s|interface\s|def\s|async def\s|struct\s|enum\s"
    r"|trait\s|impl[\s<]|module\s|namespace\s|template\s*<|virtual\s|static\s+\w)", re.I)
_LICENSE = re.compile(
    r"^(//|#|\*|--|<#)?\s*(copyright|\(c\)|licensed|spdx|see the license|limitations under"
    r"|you may not use this file|you may obtain a copy|https?://www\.apache\.org/licenses"
    r"|distributed under the license|without warranties|permission is hereby granted"
    r"|the above copyright|the software is provided|mit license|apache license)", re.I)
_LICENSE_WORD = re.compile(r"copyright|licen[cs]e|spdx", re.I)
_COMMENT = re.compile(r"^\s*(//|#(?!!)|/\*|\*|--|<#|#>)")
# Declaration-like lines in infrastructure code, scripts, templates and SQL.
_IAC = re.compile(
    r"^\s*(resource|module|variable|output|data|provider|locals|param|var|targetScope|policy|rule"
    r"|package|default\s+(allow|deny)|deny|allow|violation|function|filter|workflow|configuration"
    r"|description\s*=|\.synopsis|\.description|create\s+(or\s+replace\s+)?(table|view|function"
    r"|procedure|trigger)|[a-z_][\w-]*\s*\(\)\s*\{|[a-z_][\w.]*\s*<-\s*function"
    r"|AWSTemplateFormatVersion|Description:|Type:\s*AWS::|Transform:"
    r"|\"type\":\s*\"(Microsoft\.|AWS::)"
    r"|\"description\":|runs:|inputs:|using:|--\s+\w)", re.I)

MAX_FILE_CHARS = 1500       # extracted text kept per file
AREA_DEPTH = 3              # folders merged to this many path levels
AREA_MIN_CHARS = 300        # smaller areas carry too little to summarise
AREA_MAX_CHARS = 8000       # shared equally among the area's files


def is_source(path: str, relaxed: bool = False) -> bool:
    """A source file worth reading: allowed extension (or a deployment template); not a test,
    vendored, built or config. `relaxed` also allows examples, samples and top-level scripts or
    tools folders, for repos that have no other code (sample and automation repos)."""
    p = path.replace("\\", "/")
    if not (p.lower().endswith(SOURCE_EXT + IAC_EXT) or _TEMPLATE_PATH.search(p)):
        return False
    skip, noise = (_SKIP_RELAXED, _NOISE_RELAXED) if relaxed else (_SKIP, _NOISE)
    return not skip.search(p) and not noise.search(p)


def strip_licence_header(text: str) -> str:
    """Drop the first comment block when it is a licence or copyright notice. The per-line
    filter alone misses the block's other lines (warranty text, licence URL)."""
    lines = text.splitlines()
    i = 0
    while i < len(lines) and (lines[i].startswith("#!") or not lines[i].strip()):
        i += 1
    j = i
    while j < len(lines) and lines[j].strip() and _COMMENT.match(lines[j]):
        j += 1
    if j > i and _LICENSE_WORD.search("\n".join(lines[i:j])):
        return "\n".join(lines[:i] + lines[j:])
    return text


def looks_generated(text: str) -> bool:
    """Generated or minified, judged from the content (never from the file size)."""
    if _GENERATED.search(text[:600]):
        return True
    lines = text.splitlines() or [""]
    longest = max(len(line) for line in lines)
    avg = len(text) / len(lines)
    return longest > 2000 and avg > 300        # minified bundles: very long lines, few breaks


def extract(text: str, limit: int = MAX_FILE_CHARS, path: str = "") -> str:
    """Declaration lines and doc comments of one file, at most `limit` characters. With `path`,
    infrastructure code, scripts and templates also keep their resource and parameter lines,
    notebooks are read cell by cell, and a YAML/JSON file that is not a template yields nothing.
    NUL bytes are dropped: Postgres text cannot hold them, so one would fail the crawl."""
    low = path.lower()
    text = text.replace("\x00", "")
    if low.endswith(".ipynb"):
        try:
            cells = json.loads(text).get("cells", [])
            text = "\n".join("".join(c["source"]) if isinstance(c.get("source"), list)
                             else str(c.get("source", "")) for c in cells if isinstance(c, dict))
        except (ValueError, AttributeError):
            return ""
    elif low.endswith((".yaml", ".yml", ".json")) and not _TEMPLATE_BODY.search(text[:5000]):
        return ""
    iac = bool(low) and not low.endswith(SOURCE_EXT)
    out, n = [], 0
    for line in strip_licence_header(text).splitlines():
        s = line.strip()
        if (not s or len(s) > 200 or _LICENSE.match(s)
                or not (_DECL.match(line) or (iac and _IAC.match(line)))):
            continue
        s = s.rstrip("{").strip()
        out.append(s)
        n += len(s) + 1
        if n > limit:
            break
    return "\n".join(out)


# ---------------------------------------------------------------- secret filter

_SECRET_PATTERNS = [
    re.compile(r"-----BEGIN [A-Z ]*PRIVATE KEY-----.*?-----END [A-Z ]*PRIVATE KEY-----", re.S),
    re.compile(r"\bAKIA[0-9A-Z]{16}\b"),                                  # AWS access key id
    re.compile(r"\b(ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9]{30,}\b"),            # GitHub tokens
    re.compile(r"\bgithub_pat_[A-Za-z0-9_]{40,}\b"),
    re.compile(r"\b(sk|rk|pk)[-_](live|test|ant|proj)?[-_]?[A-Za-z0-9_\-]{20,}\b"),
    re.compile(r"\bgsk_[A-Za-z0-9]{20,}\b"),
    re.compile(r"\bxox[abposr]-[A-Za-z0-9-]{10,}\b"),                    # Slack
    re.compile(r"\beyJ[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\.[A-Za-z0-9_-]{10,}\b"),  # JWT
    re.compile(r"\bAIza[0-9A-Za-z_\-]{35}\b"),                            # Google API key
]
_ASSIGNED = re.compile(
    r"(?i)\b([A-Za-z0-9_]*(password|passwd|secret|token|api[_-]?key|access[_-]?key|private[_-]?key"
    r"|client[_-]?secret|credential)[A-Za-z0-9_]*)\s*[:=]\s*([\"'`])([^\"'`\s]{6,})\3")
_URL_CREDS = re.compile(r"(\b[a-z][a-z0-9+.-]*://)[^/\s:@]+:[^/\s@]+@", re.I)
_INTERNAL_HOST = re.compile(
    r"\b[a-z0-9-]+(\.[a-z0-9-]+)*\.(internal|corp|local|lan|intranet|private)\b"
    r"|\b(10\.\d{1,3}\.\d{1,3}\.\d{1,3}|192\.168\.\d{1,3}\.\d{1,3}|172\.(1[6-9]|2\d|3[01])\.\d{1,3}\.\d{1,3})\b",
    re.I)
_LONG_OPAQUE = re.compile(r"([\"'`])([A-Za-z0-9+/=_\-]{40,})\1")


def scrub(text: str) -> str:
    """Remove secrets and internal hostnames. Runs before anything is stored or sent to a model."""
    for pat in _SECRET_PATTERNS:
        text = pat.sub("<secret>", text)
    text = _ASSIGNED.sub(lambda m: f"{m.group(1)} = {m.group(3)}<secret>{m.group(3)}", text)
    text = _URL_CREDS.sub(r"\1<credentials>@", text)
    text = _INTERNAL_HOST.sub("<internal-host>", text)
    return _LONG_OPAQUE.sub(lambda m: f"{m.group(1)}<opaque>{m.group(1)}", text)


# ---------------------------------------------------------------- areas

def area_of(path: str) -> str:
    folder = str(PurePosixPath(path.replace("\\", "/")).parent)
    return "/".join(folder.split("/")[:AREA_DEPTH]) if folder not in ("", ".") else "."


def build_areas(extracts: dict[str, str]) -> dict[str, dict]:
    """{area path: {"text", "files", "hash"}} from {file path: extracted text}.

    Each area's text is capped at AREA_MAX_CHARS, shared equally among its files so a large
    area is not cut off alphabetically. Areas under AREA_MIN_CHARS are dropped, unless every
    area is that small (a tiny repo is still read)."""
    by: dict[str, list[tuple[str, str]]] = {}
    for path, ex in sorted(extracts.items()):
        if ex:
            by.setdefault(area_of(path), []).append((path, ex))
    sizes = {a: sum(len(ex) + 4 for _, ex in fs) for a, fs in by.items()}
    keep_small = bool(sizes) and max(sizes.values()) < AREA_MIN_CHARS
    out = {}
    for area, files in by.items():
        blocks = [f"## {PurePosixPath(p).name}\n{ex}" for p, ex in files]
        if sum(len(b) for b in blocks) < AREA_MIN_CHARS and not keep_small:
            continue
        share = max(150, AREA_MAX_CHARS // len(blocks))
        text = "\n".join(b[:share] for b in blocks)[:AREA_MAX_CHARS]
        out[area] = {"text": text, "files": [p for p, _ in files],
                     "hash": hashlib.sha256(text.encode("utf-8")).hexdigest()[:32]}
    return out


# ---------------------------------------------------------------- code words

# Identifiers worth splitting: dotted, snake or kebab names and camelCase / PascalCase.
_IDENT = re.compile(r"[A-Za-z][A-Za-z0-9]*(?:[._\-][A-Za-z0-9]+)+"
                    r"|[a-z]+[A-Z][A-Za-z0-9]*|[A-Z][a-z0-9]+[A-Z][A-Za-z0-9]*"
                    r"|[A-Z]{2,}[a-z][A-Za-z0-9]*")
_PARTS = re.compile(r"[A-Z]+(?![a-z])|[A-Z]?[a-z]+|[0-9]+")
CODE_WORDS_MAX_CHARS = 100_000


def split_identifier(tok: str) -> str:
    """getUserToken -> 'get user token'; http_retry.backoff -> 'http retry backoff'."""
    return " ".join(p.lower() for p in _PARTS.findall(tok))


def code_words(text: str) -> str:
    """Text for the code-words keyword list: each identifier kept and followed by its parts,
    so both 'getUserToken' and 'user token' match. Input is already extracted and scrubbed."""
    text = text[:CODE_WORDS_MAX_CHARS].replace("\x00", " ")
    return _IDENT.sub(lambda m: f"{m.group(0)} {split_identifier(m.group(0))}", text)
